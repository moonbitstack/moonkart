"""Generate `src/lru_differential_wbtest.mbt` from two reference implementations.

The same 500-request trace goes through `functools.lru_cache` from the Python
standard library and through `cachetools.LRUCache`. Neither implementation lives
in this repository, and the script refuses to emit anything unless the two agree
on every request, so the recorded hits and misses are not this library's opinion
of its own behaviour.

Run only when the trace changes, then `moon fmt`; the output is committed. The
generator needs `cachetools`, which CI does not install.

Usage: python3 scripts/gen_lru_vectors.py
"""

import functools
import pathlib
import sys

from cachetools import LRUCache

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "lru_differential_wbtest.mbt"
CAP = 12
HOT = 200
SCAN = 150
MIXED = 150

HEADER = '''// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by scripts/gen_lru_vectors.py; change the trace there, not here.
//
// A trace of TOTAL requests and the hit-or-miss answers that two independent
// least-recently-used implementations give for it at a capacity of CAP:
// `functools.lru_cache` from the Python standard library, and
// `cachetools.LRUCache`. They agree on every request, which is what makes this a
// reference rather than a snapshot of this library.
//
// The trace is a hot working set, then a scan of one-hit wonders, then a mixed
// phase, so every way of getting recency wrong shows up as a divergence.

///|
fn reference_trace() -> Array[Int] {
'''


def trace():
    """A hot working set, then a scan of one-hit wonders, then a mixed phase."""
    state = 20260101
    keys = []

    def below(bound):
        nonlocal state
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        return state % bound

    for _ in range(HOT):
        keys.append(below(10))
    for i in range(SCAN):
        keys.append(60 + i)
    for _ in range(MIXED):
        keys.append(below(41))
    return keys


def stdlib_hits(keys):
    calls = {"n": 0}

    @functools.lru_cache(maxsize=CAP)
    def read(key):
        calls["n"] += 1
        return key

    out = []
    for key in keys:
        before = calls["n"]
        read(key)
        out.append(1 if calls["n"] == before else 0)
    return out


def cachetools_hits(keys):
    cache = LRUCache(maxsize=CAP)
    out = []
    for key in keys:
        if key in cache:
            cache[key] = cache[key]
            out.append(1)
        else:
            cache[key] = key
            out.append(0)
    return out


def array(values, per_line=20):
    rows = []
    for i in range(0, len(values), per_line):
        rows.append("  " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return "[\n" + "\n".join(rows) + "\n]"


def main():
    keys = trace()
    a = stdlib_hits(keys)
    b = cachetools_hits(keys)
    if a != b:
        clash = next(i for i, (x, y) in enumerate(zip(a, b)) if x != y)
        sys.exit(f"the references disagree at request {clash}")
    text = HEADER.replace("TOTAL", str(len(keys))).replace("CAP", str(CAP))
    text += array(keys) + "\n}\n\n"
    text += "///|\n"
    text += "/// 1 where the reference reported a hit, 0 where it inserted.\n"
    text += "fn reference_hits() -> Array[Int] {\n"
    text += array(a) + "\n}\n\n"
    text += '''///|
test "lru replays a trace two reference implementations agree on" {
  let keys = reference_trace()
  let want = reference_hits()
  assert_eq(keys.length(), want.length())
  let cache = lru_cache(cap=12L)
  let got : Array[Int] = []
  for key in keys {
    match cache.get(key) {
      Some(_) => got.push(1)
      None => {
        cache.set(key, key)
        got.push(0)
      }
    }
  }
  assert_eq(got, want)
  assert_eq(cache.size(), 12L)
}
'''
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(keys)} requests, {a.count(1)} hits")


if __name__ == "__main__":
    main()
